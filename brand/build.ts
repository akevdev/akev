// Writes the Akev brand SVGs next to this file, the UI favicon and the desktop splash.
// Run: bun brand/build.ts (or `make brand`, which also runs render.sh)
// Then brand/render.sh rasterises them into the desktop icons, the UI's PNG favicons
// and the installer art.
//
// The mark is a capital A drawn as a chevron, with its crossbar replaced by a single dot: the
// request Akev is holding between the two sides of a connection. All geometry is in a 1024 box
// and the mark is centred on (512, 512).
const dir = import.meta.dir;

export const INK_TOP = '#22232b';
export const INK_BOTTOM = '#0d0e12';
export const VIOLET = '#8a70ff'; // the dot on ink; in the UI it is var(--accent)

/** The chevron. A thin same-colour stroke rounds its corners. */
export const CHEVRON = 'M512 280 748 744H656L512 460.9 368 744H276Z';
export const CHEVRON_STROKE = 24;
export const DOT = { cx: 512, cy: 684, r: 62 };

/** A superellipse ("squircle"): smoother corners than a rounded rectangle. */
function squircle(half: number, n = 5): string {
  const pts: string[] = [];
  for (let deg = 0; deg < 360; deg += 3) {
    const t = (deg * Math.PI) / 180;
    const c = Math.cos(t);
    const s = Math.sin(t);
    const x = 512 + half * Math.sign(c) * Math.abs(c) ** (2 / n);
    const y = 512 + half * Math.sign(s) * Math.abs(s) ** (2 / n);
    pts.push(`${+x.toFixed(1)} ${+y.toFixed(1)}`);
  }
  return `M${pts.join('L')}Z`;
}

const mark = (legs: string, dot: string) =>
  `  <path d="${CHEVRON}" fill="${legs}" stroke="${legs}" stroke-width="${CHEVRON_STROKE}" stroke-linejoin="round"/>
  <circle cx="${DOT.cx}" cy="${DOT.cy}" r="${DOT.r}" fill="${dot}"/>`;

const tile = (viewBox: string, size: string) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}"${size}>
  <defs>
    <linearGradient id="ink" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="${INK_TOP}"/>
      <stop offset="1" stop-color="${INK_BOTTOM}"/>
    </linearGradient>
  </defs>
  <path d="${squircle(440)}" fill="url(#ink)"/>
  <path d="${squircle(437)}" fill="none" stroke="#fff" stroke-opacity=".1" stroke-width="6"/>
${mark('#fff', VIOLET)}
</svg>
`;

// App icon: the ink tile with the platform's usual margin around it.
await Bun.write(`${dir}/akev-icon.svg`, tile('0 0 1024 1024', ' width="1024" height="1024"'));
// Favicon: the same tile, full bleed.
await Bun.write(`${dir}/../ui/public/favicon.svg`, tile('72 72 880 880', ''));
// Bare mark for use on any surface: legs take the text colour, the dot stays violet.
await Bun.write(
  `${dir}/akev-mark.svg`,
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="240 240 544 544">
${mark('currentColor', VIOLET)}
</svg>
`,
);

// Desktop splash (shown until the UI loads): the mark on the UI's dark or light background,
// following the system theme. Colours are the UI's `--bg-app`, `--text`, `--text-muted` and
// `--accent` tokens (ui/src/styles/tokens.css).
await Bun.write(
  `${dir}/../desktop/splash/index.html`,
  `<!doctype html>
<!-- Generated by brand/build.ts. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="color-scheme" content="dark light">
<title>Akev</title>
<style>
:root{--bg:#0a0b0e;--text:#e8eaef;--muted:#a0a6b3;--accent:#7556ff}
@media (prefers-color-scheme:light){:root{--bg:#eceef2;--text:#14161c;--muted:#4f5563;--accent:#6e50f0}}
html,body{margin:0;height:100%;background:var(--bg);color:var(--muted);font:13px/1.4 system-ui,-apple-system,"Segoe UI",sans-serif}
body{display:grid;place-items:center}
main{display:flex;flex-direction:column;align-items:center;gap:18px}
svg{width:56px;height:56px;color:var(--text);animation:pulse 2.4s ease-in-out infinite}
@keyframes pulse{50%{opacity:.55}}
@media (prefers-reduced-motion:reduce){svg{animation:none}}
</style>
</head>
<body>
<main role="status" aria-live="polite">
<svg viewBox="240 240 544 544" aria-hidden="true">
${mark('currentColor', 'var(--accent)')}
</svg>
<div>Starting Akev…</div>
</main>
</body>
</html>
`,
);
