/** Mock snippet generation for the codegen endpoints (a handful of real targets). */

import { base64ToText } from '../../lib/encoding';
import type { CodegenTarget, EditableRequest, Snippet } from '../types';
import { CODEGEN_TARGETS } from './data';

function shellQuote(s: string): string {
  return `'${s.replace(/'/g, `'\\''`)}'`;
}

function bodyText(req: EditableRequest): string | null {
  if (!req.body) return null;
  return base64ToText(req.body) ?? '<binary body>';
}

const SKIP = new Set([':authority', ':method', ':path', ':scheme', 'host', 'content-length', 'connection', 'accept-encoding']);

function headers(req: EditableRequest): [string, string][] {
  return req.headers.filter(([k]) => !SKIP.has(k.toLowerCase()));
}

export function generateSnippet(req: EditableRequest, target: CodegenTarget): Snippet {
  const info = CODEGEN_TARGETS.find((t) => t.id === target);
  const language = info?.language ?? 'text';
  const body = bodyText(req);
  const hs = headers(req);
  let code: string;
  switch (target) {
    case 'curl':
    case 'curl-windows': {
      const nl = target === 'curl' ? ' \\\n  ' : ' ^\n  ';
      const q = target === 'curl' ? shellQuote : (s: string) => `"${s.replace(/"/g, '\\"')}"`;
      const parts = [`curl${req.method === 'GET' ? '' : ` -X ${req.method}`} ${q(req.url)}`];
      for (const [k, v] of hs) parts.push(`-H ${q(`${k}: ${v}`)}`);
      if (body) parts.push(`--data-raw ${q(body)}`);
      code = parts.join(nl);
      break;
    }
    case 'httpie':
      code = `http ${req.method} ${shellQuote(req.url)}${hs.map(([k, v]) => ` \\\n  ${shellQuote(`${k}:${v}`)}`).join('')}${body ? ` \\\n  --raw ${shellQuote(body)}` : ''}`;
      break;
    case 'wget':
      code = `wget --method=${req.method}${hs.map(([k, v]) => ` \\\n  --header=${shellQuote(`${k}: ${v}`)}`).join('')}${body ? ` \\\n  --body-data=${shellQuote(body)}` : ''} \\\n  -O - ${shellQuote(req.url)}`;
      break;
    case 'js-fetch':
    case 'node-fetch':
      code = `${target === 'node-fetch' ? '// Node.js 18+ has fetch built in\n' : ''}const response = await fetch(${JSON.stringify(req.url)}, {
  method: ${JSON.stringify(req.method)},
  headers: ${JSON.stringify(Object.fromEntries(hs), null, 2).replace(/\n/g, '\n  ')},${body ? `\n  body: ${JSON.stringify(body)},` : ''}
});
console.log(response.status, await response.text());`;
      break;
    case 'node-axios':
      code = `import axios from 'axios';

const { status, data } = await axios({
  method: ${JSON.stringify(req.method.toLowerCase())},
  url: ${JSON.stringify(req.url)},
  headers: ${JSON.stringify(Object.fromEntries(hs), null, 2).replace(/\n/g, '\n  ')},${body ? `\n  data: ${JSON.stringify(body)},` : ''}
});
console.log(status, data);`;
      break;
    case 'python-requests':
    case 'python-httpx': {
      const lib = target === 'python-requests' ? 'requests' : 'httpx';
      code = `import ${lib}

response = ${lib}.request(
    ${JSON.stringify(req.method)},
    ${JSON.stringify(req.url)},
    headers={
${hs.map(([k, v]) => `        ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n')}
    },${body ? `\n    content=${JSON.stringify(body)},`.replace('content=', lib === 'requests' ? 'data=' : 'content=') : ''}
)
print(response.status_code, response.text)`;
      break;
    }
    case 'go-net-http':
      code = `package main

import (
\t"fmt"
\t"io"
\t"net/http"${body ? '\n\t"strings"' : ''}
)

func main() {
\treq, _ := http.NewRequest(${JSON.stringify(req.method)}, ${JSON.stringify(req.url)}, ${body ? `strings.NewReader(${JSON.stringify(body)})` : 'nil'})
${hs.map(([k, v]) => `\treq.Header.Set(${JSON.stringify(k)}, ${JSON.stringify(v)})`).join('\n')}
\tres, err := http.DefaultClient.Do(req)
\tif err != nil {
\t\tpanic(err)
\t}
\tdefer res.Body.Close()
\tb, _ := io.ReadAll(res.Body)
\tfmt.Println(res.StatusCode, string(b))
}`;
      break;
    case 'raw-http': {
      let path = req.url;
      let host = '';
      try {
        const u = new URL(req.url);
        path = `${u.pathname}${u.search}`;
        host = u.host;
      } catch {
        // keep raw
      }
      code = `${req.method} ${path} HTTP/1.1\r\nHost: ${host}\r\n${hs.map(([k, v]) => `${k}: ${v}`).join('\r\n')}\r\n\r\n${body ?? ''}`;
      break;
    }
    default:
      code = `// ${info?.name ?? target} snippet (generated by the mock backend)\n// ${req.method} ${req.url}\n${hs.map(([k, v]) => `// ${k}: ${v}`).join('\n')}${body ? `\n// body: ${body.slice(0, 200)}` : ''}`;
  }
  return { target, language, code };
}
