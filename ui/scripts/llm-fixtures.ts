/** SSE events (`event:` + joined `data:` lines) of a body. */
function sseEvents(text: string): { event?: string; data: string }[] {
  const out: { event?: string; data: string }[] = [];
  for (const block of text.replace(/\r\n/g, '\n').split('\n\n')) {
    let event: string | undefined;
    const data: string[] = [];
    for (const line of block.split('\n')) {
      if (line.startsWith('event:')) event = line.slice(6).trim();
      else if (line.startsWith('data:')) data.push(line.slice(line[5] === ' ' ? 6 : 5));
    }
    if (data.length) out.push(event ? { event, data: data.join('\n') } : { data: data.join('\n') });
  }
  return out;
}

const items = SCENARIOS.map((s) => {
  const sse = s.contentType.startsWith('text/event-stream');
  const args = ['run', '-q', '-p', 'akev-content', '--example', 'llm_parse', '--', `host=${s.host}`, `port=${s.port}`, `path=${s.path}`, `request=${FIXTURES}${s.request}`, `response=${FIXTURES}${s.response}`, `status=${s.status}`, `content-type=${s.contentType}`];
  if (sse) args.push('event-step=1');
  const run = Bun.spawnSync(['cargo', ...args], { cwd: ROOT, stderr: 'inherit' });
  if (run.exitCode !== 0) throw new Error(`llm_parse failed for ${s.id}`);
  const llm = JSON.parse(run.stdout.toString()) as { timing: { ttftMs?: number } };
  const first = llm.timing.ttftMs;
  llm.timing = {}; // the mock fills timing in from its own clock
  const responseBody = readFileSync(join(ROOT, FIXTURES, s.response), 'utf8');
  return {
    id: s.id,
    host: s.host,
    port: s.port,
    scheme: s.scheme,
    path: s.path,
    status: s.status,
    source: s.source,
    latency: s.latency,
    requestBody: readFileSync(join(ROOT, FIXTURES, s.request), 'utf8'),
    responseBody,
    contentType: s.contentType,
    events: sse ? sseEvents(responseBody) : null,
    firstTokenEvent: sse && first != null ? Math.round(first) : null,
    llm,
  };
});

