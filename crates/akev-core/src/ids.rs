use serde::{Deserialize, Serialize};
use std::fmt;
use std::sync::atomic::{AtomicU64, Ordering};

/// Identifier of a captured exchange (HTTP request/response, WebSocket session, TLS failure, tunnel...).
///
/// IDs are allocated monotonically per daemon process, so sorting by ID == sorting by start order.
/// Serialized as a plain JSON number (safe up to 2^53 in JS, which we will never reach).
#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(transparent)]
pub struct ExchangeId(pub u64);

impl fmt::Debug for ExchangeId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "#{}", self.0)
    }
}
impl fmt::Display for ExchangeId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.0)
    }
}

/// Identifier of a client connection (TCP connection accepted by the proxy). Many exchanges
/// may share one connection (keep-alive, HTTP/2 multiplexing).
#[derive(
    Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize, Debug, Default,
)]
#[serde(transparent)]
pub struct ConnectionId(pub u64);

impl fmt::Display for ConnectionId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.0)
    }
}

/// Rule identifiers are UUID strings (generated by the UI or the API) so rule sets can be
/// exported/imported and merged without clashes.
pub type RuleId = String;

static NEXT_EXCHANGE: AtomicU64 = AtomicU64::new(1);
static NEXT_CONNECTION: AtomicU64 = AtomicU64::new(1);

impl ExchangeId {
    /// Allocate the next process-wide exchange id.
    pub fn next() -> Self {
        ExchangeId(NEXT_EXCHANGE.fetch_add(1, Ordering::Relaxed))
    }

    /// Reserve `count` consecutive ids and return the first: later allocations are all greater,
    /// so exchanges inserted with them afterwards (e.g. a session restored in the background)
    /// still sort before traffic captured meanwhile.
    pub fn reserve(count: u64) -> Self {
        ExchangeId(NEXT_EXCHANGE.fetch_add(count, Ordering::Relaxed))
    }
}

impl ConnectionId {
    pub fn next() -> Self {
        ConnectionId(NEXT_CONNECTION.fetch_add(1, Ordering::Relaxed))
    }
}

/// Generate a new random UUID string (used for rule ids etc).
pub fn new_uuid() -> String {
    uuid::Uuid::new_v4().to_string()
}
